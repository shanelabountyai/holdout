// Builds the browser snippet (src/sdk/snippet.ts → sdk/holdout.js) with esbuild. One function, used by
// `npm run sdk:build` (scripts/build-sdk.ts) and by tests/sdk/vectors.test.ts, which fails if the committed file is stale.
import { buildSync } from 'esbuild';

export const SNIPPET_ENTRY = 'src/sdk/snippet.ts';
export const SNIPPET_OUT = 'sdk/holdout.js';

export function buildSnippet(): string {
  const r = buildSync({
    entryPoints: [SNIPPET_ENTRY],
    bundle: true,
    format: 'iife',
    globalName: 'Holdout',
    platform: 'browser',
    target: 'es2018',
    charset: 'utf8',
    legalComments: 'none',
    minify: false,
    write: false,
    banner: { js: '/* Holdout snippet — generated by `npm run sdk:build` from src/sdk/snippet.ts. Do not edit. */' },
  });
  return r.outputFiles[0]!.text;
}
